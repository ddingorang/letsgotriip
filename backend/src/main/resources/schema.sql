CREATE TABLE users (
    user_id BIGINT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL DEFAULT 'USER', -- USER / ADMIN / MANAGER
    job_group VARCHAR(30) DEFAULT NULL, -- 개발 / 기획 / 디자인 / 영업
    region VARCHAR(30) DEFAULT NULL, -- 서울 / 경기 / 부산 (대략)
    birthday DATE DEFAULT NULL, -- 생년월일 (나이/연령대 파생 가능)
    joined_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

